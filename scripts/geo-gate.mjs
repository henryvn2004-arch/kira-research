#!/usr/bin/env node
// geo-gate.mjs — code gate (no model) for GEO answer rows before they reach the database.
//
// Input: a JSON file { answers: [...], field_claims: [...] } written by an extraction run,
// plus the source text the rows were cut from (files and/or a list of number tokens).
// Every row gets gate = { ok, reasons[] } and status 'draft' (passed) or 'rejected'.
//
// Checks
//   all rows    every number in the text appears in the source; no person names; KIRA copy rules
//   answers     question ends with "?", answer_short <= 50 words, cites a source,
//               numeric intents carry a number and a year
//   transcript  answer_short carries the basis label ("KIRA field research (...)"),
//               the field insight leads (no number before the first ';' or '('),
//               a sourced number reads "... (<source>), as cited in <basis label>";
//               no wording that suggests one named person was interviewed
//
// Usage
//   node scripts/geo-gate.mjs --rows rows.json --source a.txt [--source b.txt] [--numbers nums.json]
//        [--out gated.json] [--sql insert.sql] [--insert]
//   --numbers  JSON array of number tokens found in the source (when the text itself is not at hand)
//   --sql      write an idempotent INSERT (on conflict (content_hash) do nothing) for passed rows
//   --insert   upsert passed rows through Supabase REST (needs SUPABASE_URL + SUPABASE_SERVICE_KEY)
//   --status   status for passed rows (default draft; the runner hook uses published)

import fs from 'node:fs';
import crypto from 'node:crypto';

const args = process.argv.slice(2);
const opt = (k) => { const i = args.indexOf(k); return i >= 0 ? args[i + 1] : null; };
const many = (k) => args.flatMap((a, i) => (a === k ? [args[i + 1]] : []));

const INTENTS = new Set(['market_size', 'growth', 'key_players', 'channels', 'margins', 'pricing', 'regulation', 'entry',
  'trade_flow', 'consumer', 'trends', 'practitioner', 'investment', 'risks', 'other']);
const NUMERIC_INTENTS = new Set(['market_size', 'growth', 'margins', 'pricing', 'trade_flow']);
const TOPICS = new Set(['margins', 'payment_terms', 'exclusivity', 'decision_makers', 'switching_triggers', 'channel',
  'lead_times', 'pricing', 'buyer_roles', 'risk', 'regulation', 'competition', 'other']);
const COUNTRIES = new Set(['VN', 'TH', 'SG', 'ID', 'MY', 'PH', 'JP', 'KR', 'TW', 'AU', 'NZ', 'KH', 'LA', 'MM', 'BN', 'CN', 'IN']);

// KIRA copy rules: no positioning as a tool, no model names, no competitor research houses.
const BANNED = [
  /\bAI[- ](powered|generated|driven|written)\b/i, /\bgenerated by (an? )?AI\b/i, /\blanguage model\b/i,
  /\bLLMs?\b/, /\bChatGPT\b/i, /\bGPT-?\d/i, /\bClaude\b/, /\bAnthropic\b/, /\bMcKinsey\b/i,
  /\bMordor\b/i, /\bFrost\b/, /\bEuromonitor\b/i, /\bSynovate\b/i, /\bIpsos\b/i, /\bour platform\b/i,
];
// Person names: honorific + capitalised word (EN and the local forms used in our markets).
const HONORIFIC = /\b(Mr|Mrs|Ms|Mdm|Miss|Dr|Prof|Sir|Madam|Bapak|Pak|Ibu|Bu|Khun|Anh|Chị|Ông|Bà|Mas|Mbak)\.?\s+\p{Lu}/u;
// A single named or identifiable person "was interviewed" framing.
const ONE_PERSON = /\b(told (us|KIRA|our analysts?)|in an interview with|interviewed (a|an|one)\b|our interviewee|the expert (said|told|explained)|he said|she said)\b/i;
// A KIRA segment key (tax_industries.slug): "industry--segment" for level 2, or a bare industry slug some topics use.
const SEGMENT = /^[a-z0-9]+(?:-[a-z0-9]+)*(?:--[a-z0-9]+(?:-[a-z0-9]+)*)?$/;
const BASIS = /^KIRA field research \(.{10,}\)$/;

const NUM_RE = /\d[\d,.]*\d|\d/g;
const normNum = (t) => {
  let s = String(t).replace(/,/g, '').replace(/\.$/, '');
  if (s.includes('.')) s = s.replace(/0+$/, '').replace(/\.$/, '');
  return s;
};
const numbersIn = (text) => (String(text || '').match(NUM_RE) || []).map(normNum);
const words = (s) => String(s || '').trim().split(/\s+/).filter(Boolean).length;
const hash = (...p) => crypto.createHash('sha1').update(p.map((x) => (typeof x === 'string' ? x : JSON.stringify(x ?? ''))).join('␟')).digest('hex');

function sourceNumbers() {
  const set = new Set();
  for (const f of many('--source')) {
    let t = fs.readFileSync(f, 'utf8');
    // HTML source: count only visible text, not CSS, scripts, attributes or inline images.
    if (/\.html?$/i.test(f)) t = t.replace(/<(script|style)[\s\S]*?<\/\1>/gi, ' ').replace(/<[^>]+>/g, ' ');
    for (const n of numbersIn(t)) set.add(n);
  }
  const nf = opt('--numbers');
  if (nf) for (const n of JSON.parse(fs.readFileSync(nf, 'utf8'))) set.add(normNum(n));
  return set;
}

function common(text, src, reasons) {
  const missing = [...new Set(numbersIn(text))].filter((n) => !src.has(n));
  if (missing.length) reasons.push(`number not in source: ${missing.join(', ')}`);
  if (HONORIFIC.test(text)) reasons.push('person name (honorific)');
  for (const re of BANNED) if (re.test(text)) reasons.push(`copy rule: ${re}`);
}

function gateAnswer(r, src) {
  const reasons = [];
  if (!r.question || !/\?\s*$/.test(r.question)) reasons.push('question must end with ?');
  if (!INTENTS.has(r.intent)) reasons.push(`intent ${r.intent}`);
  if (!COUNTRIES.has(r.country_code)) reasons.push(`country ${r.country_code}`);
  if (!['report', 'transcript', 'insight', 'econ'].includes(r.source_kind)) reasons.push(`source_kind ${r.source_kind}`);
  if (!r.source_ref?.slug) reasons.push('source_ref.slug missing');
  if (r.segment_key != null && !SEGMENT.test(r.segment_key)) reasons.push('segment_key must be a segment slug or null');
  const a = r.answer_short || '';
  if (words(a) > 50) reasons.push(`answer_short ${words(a)} words > 50`);
  if (!/KIRA/.test(a) && !(r.primary_source && a.includes(r.primary_source))) reasons.push('answer does not name its source');
  // Transcript field statements carry no numbers by design, so the numeric rule applies to the other kinds only.
  if (NUMERIC_INTENTS.has(r.intent) && r.source_kind !== 'transcript') {
    if (!numbersIn(a).length) reasons.push('numeric intent without a number');
    if (!/\b(19|20)\d\d\b/.test(a)) reasons.push('numeric intent without a year');
  }
  const badValue = numbersIn(r.value).filter((n) => !src.has(n));
  if (badValue.length) reasons.push(`value ${r.value} not in source`);
  if (r.source_kind === 'transcript') {
    const label = r.basis_label || docBasis;
    if (!label || !BASIS.test(label)) reasons.push('transcript row without a valid basis label');
    else if (!a.includes(label)) reasons.push('answer_short does not carry the basis label');
    // A number in a transcript answer comes from a dated public source, never from the interviews:
    // say so, so the label does not read as the origin of the number.
    const nonYear = numbersIn(a.replace(label, '')).filter((n) => !/^(19|20)\d\d$/.test(n));
    if (nonYear.length && label && !a.includes(`as cited in ${label}`)) reasons.push('sourced number without "as cited in <basis label>"');
    // The field insight leads; a public number may only follow it (after ';' or inside the source parenthesis).
    const lead = a.split(/[;(]/)[0];
    if (numbersIn(lead).some((n) => !/^(19|20)\d\d$/.test(n))) reasons.push('transcript answer leads with a public number, not the field insight');
    if (ONE_PERSON.test(a)) reasons.push('one-person interview framing');
  }
  common(`${r.question} ${a}`, src, reasons);
  return reasons;
}

function gateClaim(c, src) {
  const reasons = [];
  if (!TOPICS.has(c.topic)) reasons.push(`topic ${c.topic}`);
  if (!COUNTRIES.has(c.country_code)) reasons.push(`country ${c.country_code}`);
  if (!c.transcript_slug) reasons.push('transcript_slug missing');
  if (!c.speaker_role) reasons.push('speaker_role missing');
  // BizDirect matches claims on country_code + industry == segment_key: a level-2 slug or nothing.
  if (c.industry != null && !SEGMENT.test(c.industry)) reasons.push('industry must be a segment slug or null');
  if (!c.basis_label || !BASIS.test(c.basis_label)) reasons.push('basis_label missing or malformed');
  if (words(c.claim_text) > 60) reasons.push(`claim_text ${words(c.claim_text)} words > 60`);
  if (ONE_PERSON.test(c.claim_text)) reasons.push('one-person interview framing');
  common(`${c.speaker_role} ${c.claim_text}`, src, reasons);
  return reasons;
}

const rows = JSON.parse(fs.readFileSync(opt('--rows'), 'utf8'));
// kira_answers has no basis_label column: a transcript's label comes from the file (rows.basis_label or its field claims).
const docBasis = rows.basis_label || (rows.field_claims || []).find((c) => c.basis_label)?.basis_label || null;
const src = sourceNumbers();
const passStatus = opt('--status') || 'draft';
const now = new Date().toISOString();
const stamp = (r, reasons) => ({ ...r, gate: { ok: !reasons.length, reasons }, checked_at: now, status: reasons.length ? 'rejected' : passStatus });

const answers = (rows.answers || []).map((r) => {
  const a = stamp(r, gateAnswer(r, src));
  a.content_hash = hash(a.question, a.answer_short, a.source_ref?.slug);
  return a;
});
const claims = (rows.field_claims || []).map((c) => {
  const x = stamp(c, gateClaim(c, src));
  x.content_hash = hash(x.claim_text, x.transcript_slug);
  return x;
});

const out = { answers, field_claims: claims };
if (opt('--out')) fs.writeFileSync(opt('--out'), JSON.stringify(out, null, 2));
const tally = (xs) => `${xs.filter((x) => x.gate.ok).length}/${xs.length} passed`;
console.log(`answers ${tally(answers)} · field_claims ${tally(claims)}`);
for (const x of [...answers, ...claims].filter((y) => !y.gate.ok)) console.log(`  ✗ ${(x.question || x.claim_text).slice(0, 70)} — ${x.gate.reasons.join('; ')}`);

const A_COLS = ['question', 'intent', 'country_code', 'segment_key', 'brand', 'metric', 'answer_short', 'value', 'unit', 'year', 'as_of',
  'primary_source', 'source_kind', 'source_ref', 'home', 'i18n', 'status', 'gate', 'checked_at', 'content_hash'];
const C_COLS = ['topic', 'industry', 'country_code', 'speaker_role', 'claim_text', 'transcript_slug', 'section', 'basis_label', 'i18n',
  'status', 'gate', 'checked_at', 'content_hash'];
const pick = (r, cols) => Object.fromEntries(cols.filter((c) => r[c] !== undefined).map((c) => [c, r[c]]));
const passedA = answers.filter((x) => x.gate.ok).map((r) => pick(r, A_COLS));
const passedC = claims.filter((x) => x.gate.ok).map((r) => pick(r, C_COLS));

if (opt('--sql')) {
  // Column list so id/created_at/updated_at take their defaults.
  const insCols = (table, cols, recs) => (recs.length
    ? `insert into public.${table} (${cols.join(',')}) select ${cols.join(',')} from jsonb_populate_recordset(null::public.${table}, $j$${JSON.stringify(recs).replace(/\$j\$/g, '')}$j$::jsonb) on conflict (content_hash) do nothing;\n`
    : '');
  fs.writeFileSync(opt('--sql'), insCols('kira_answers', A_COLS, passedA) + insCols('field_claims', C_COLS, passedC));
}

if (args.includes('--insert')) {
  const { SUPABASE_URL: url, SUPABASE_SERVICE_KEY: key } = process.env;
  if (!url || !key) { console.error('--insert needs SUPABASE_URL and SUPABASE_SERVICE_KEY'); process.exit(2); }
  for (const [table, recs] of [['kira_answers', passedA], ['field_claims', passedC]]) {
    if (!recs.length) continue;
    const res = await fetch(`${url}/rest/v1/${table}?on_conflict=content_hash`, {
      method: 'POST',
      headers: { apikey: key, Authorization: `Bearer ${key}`, 'Content-Type': 'application/json', Prefer: 'resolution=ignore-duplicates,return=minimal' },
      body: JSON.stringify(recs),
    });
    if (!res.ok) { console.error(`${table}: ${res.status} ${await res.text()}`); process.exit(1); }
    console.log(`${table}: ${recs.length} sent`);
  }
}
