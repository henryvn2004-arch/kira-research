#!/usr/bin/env node
// Keep the chart colours of a report's SVG exhibits working inside an insight article.
//
// A report styles its charts with plain class rules in templates/master_styles.css
// (.ex-dot-hl { fill: ... }, .svg-label { font-size: ... }). The insight page does not load that file, so a
// chart copied from a report (scripts/extract-insight-pages.mjs) would fall back to black. This script copies
// those rules into public/css/kira.css, scoped under `.article-body svg`, between two marker comments.
//
//   node scripts/sync-insight-chart-css.mjs           rewrite the block in public/css/kira.css
//   node scripts/sync-insight-chart-css.mjs --check   exit 1 when the block is out of date (no write)
//
// A rule is copied when every selector is a plain class selector (.a or .a.b) and every declaration is an SVG
// paint/text property. Classes the site already styles by hand (the 8 under "Inline SVG charts") are skipped.
// CSS variables the copied rules use that kira.css does not define are defined on `.article-body svg`.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { svgClassRules } from './lib/css-rules.mjs';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..', '..', '..');
const MASTER = path.join(ROOT, 'skills', 'kira-research-report', 'templates', 'master_styles.css');
const SITE = path.join(ROOT, 'public', 'css', 'kira.css');
const BEGIN = '/* BEGIN report-chart-css (generated by skills/kira-research-report/scripts/sync-insight-chart-css.mjs from templates/master_styles.css; do not edit by hand) */';
const END = '/* END report-chart-css */';
const HAND_MADE = new Set(['axis-text', 'axis-line', 'grid-line', 'bar-primary', 'bar-secondary', 'bar-tertiary', 'label-data', 'label-small']);

const master = fs.readFileSync(MASTER, 'utf8').replace(/\/\*[\s\S]*?\*\//g, '');
let site = fs.readFileSync(SITE, 'utf8');

const out = [];
const vars = new Set();
for (const { selectors, decls } of svgClassRules(master)) {
  const keep = selectors.filter(s => !s.slice(1).split('.').every(c => HAND_MADE.has(c)));
  if (!keep.length) continue;
  for (const [, v] of decls) for (const m of v.matchAll(/var\(\s*(--[\w-]+)/g)) vars.add(m[1]);
  out.push(`${keep.map(s => '.article-body svg ' + s).join(', ')} { ${decls.map(([p, v]) => `${p}: ${v}`).join('; ')}; }`);
}

// Variables the site does not define itself.
const siteBare = site.includes(BEGIN) ? site.slice(0, site.indexOf(BEGIN)) + site.slice(site.indexOf(END) + END.length) : site;
const missing = [...vars].filter(v => !new RegExp(`${v}\\s*:`).test(siteBare)).sort();
const defs = missing.map(v => {
  const m = master.match(new RegExp(`${v}\\s*:\\s*([^;}]+)`));
  if (!m) console.error(`warning: ${v} is used by a chart rule but defined nowhere`);
  return m ? `${v}: ${m[1].trim()}` : null;
}).filter(Boolean);

const block = [BEGIN, ...(defs.length ? [`.article-body svg { ${defs.join('; ')}; }`] : []), ...out, END].join('\n');

let next;
if (site.includes(BEGIN)) {
  next = site.slice(0, site.indexOf(BEGIN)) + block + site.slice(site.indexOf(END) + END.length);
} else {
  const anchor = site.indexOf('.article-body svg .label-small');
  if (anchor < 0) { console.error('anchor ".article-body svg .label-small" not found in kira.css'); process.exit(2); }
  const eol = site.indexOf('\n', anchor);
  next = site.slice(0, eol + 1) + block + '\n' + site.slice(eol + 1);
}

if (process.argv.includes('--check')) {
  if (next !== site) { console.error('public/css/kira.css report-chart-css block is out of date: run scripts/sync-insight-chart-css.mjs'); process.exit(1); }
  console.log(`report-chart-css up to date (${out.length} rules, ${defs.length} variables)`);
} else {
  if (next !== site) fs.writeFileSync(SITE, next);
  console.log(`report-chart-css: ${out.length} rules, ${defs.length} variables defined${next === site ? ' (no change)' : ' (written)'}`);
}
