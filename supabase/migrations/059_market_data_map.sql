-- 059_market_data_map.sql — Kira Data (D3): segment ↔ HS map and partner-reported trade by product.
--   hs_codes            HS chapters/headings used on the site, labels in EN/JA/KO/ZH.
--   segment_data_map    one row per data profile: which HS codes and which indicator groups describe a segment.
--                       A report or topic finds its row by industry slug (level 2, then its level-1 parent),
--                       else by a keyword in its industry / segment / title (longest keyword wins).
--                       groups = econ_indicators.params.group values, plus 'visitors' (econ_flows VISITORS).
--   econ_flows.reporter no longer has to be one of the 15 markets: the EU and the US report trade with them.
--   data_sources        Eurostat Comext (public, no key) and US Census international trade (public domain, free key).
-- Idempotent.

alter table public.econ_flows drop constraint if exists econ_flows_reporter_fkey;

create table if not exists public.hs_codes (
  code   text primary key,          -- 2 or 4 digits
  label  jsonb not null             -- {en, ja, ko, zh}
);
alter table public.hs_codes enable row level security;

create table if not exists public.segment_data_map (
  key             text primary key,
  hs              text[] not null default '{}',
  groups          text[] not null default '{}',
  industry_slugs  text[] not null default '{}',   -- tax_industries.slug (level 1 or 2)
  keywords        text[] not null default '{}',   -- lower case, matched as whole words (a plural s/es is allowed)
  ord             integer not null default 100
);
alter table public.segment_data_map enable row level security;

